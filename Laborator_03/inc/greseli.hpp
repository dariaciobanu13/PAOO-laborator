#ifndef GRESELI_HPP
#define GRESELI_HPP

// classes written WRONG on purpose, to show what happens
// when the destructor / copy constructor / move constructor is missing

#include <cstddef>
#include <iostream>
#include <string>

// mistake 1: allocates on the heap but has no destructor -> memory leak
class EchipaFaraDestructor {
private:
    std::string nume_;
    std::string* jucatori_;

public:
    inline static int alocari = 0;

    EchipaFaraDestructor(const std::string& nume, std::size_t capacitate)
        : nume_(nume), jucatori_(new std::string[capacitate])
    {
        ++alocari;
        std::cout << "[NoDestructor] Constructor \"" << nume_ << "\": allocated players at "
                  << jucatori_ << "\n";
    }
    // missing: ~EchipaFaraDestructor() { delete[] jucatori_; }
};

// mistake 2: has a destructor but no copy constructor
// the one generated by the compiler only copies the POINTER (shallow copy)
class EchipaFaraCopy {
private:
    std::string nume_;
    std::string* jucatori_;
    std::size_t nrJucatori_;
    std::size_t capacitate_;

public:
    EchipaFaraCopy(const std::string& nume, std::size_t capacitate)
        : nume_(nume), jucatori_(new std::string[capacitate]), nrJucatori_(0), capacitate_(capacitate)
    {
        std::cout << "[NoCopy] Constructor \"" << nume_ << "\": allocated players at "
                  << jucatori_ << "\n";
    }

    ~EchipaFaraCopy()
    {
        std::cout << "[NoCopy] Destructor \"" << nume_ << "\": delete[] " << jucatori_ << "\n";
        delete[] jucatori_;
    }

    void adaugaJucator(const std::string& jucator)
    {
        if (nrJucatori_ < capacitate_) {
            jucatori_[nrJucatori_++] = jucator;
        }
    }

    void schimbaJucator(std::size_t index, const std::string& jucatorNou)
    {
        if (index < nrJucatori_) {
            jucatori_[index] = jucatorNou;
        }
    }

    void afiseaza() const
    {
        std::cout << "  \"" << nume_ << "\" (players at " << jucatori_ << "): ";
        for (std::size_t i = 0; i < nrJucatori_; ++i) {
            std::cout << jucatori_[i] << (i + 1 < nrJucatori_ ? ", " : "");
        }
        std::cout << "\n";
    }
};

// mistake 3: has destructor and copy constructor but no move constructor
// so std::move(...) doesn't move anything, it just calls the copy constructor
class EchipaFaraMove {
private:
    std::string nume_;
    std::string* jucatori_;
    std::size_t capacitate_;

public:
    EchipaFaraMove(const std::string& nume, std::size_t capacitate)
        : nume_(nume), jucatori_(new std::string[capacitate]), capacitate_(capacitate)
    {
        std::cout << "[NoMove] Constructor \"" << nume_ << "\": allocated players at "
                  << jucatori_ << "\n";
    }

    EchipaFaraMove(const EchipaFaraMove& other)
        : nume_(other.nume_), jucatori_(new std::string[other.capacitate_]),
          capacitate_(other.capacitate_)
    {
        for (std::size_t i = 0; i < capacitate_; ++i) {
            jucatori_[i] = other.jucatori_[i];
        }
        std::cout << "[NoMove] Copy constructor \"" << nume_ << "\": allocated again and copied "
                  << capacitate_ << " slots (" << other.jucatori_ << " -> " << jucatori_ << ")\n";
    }

    ~EchipaFaraMove()
    {
        std::cout << "[NoMove] Destructor \"" << nume_ << "\": delete[] " << jucatori_ << "\n";
        delete[] jucatori_;
    }
};

#endif
