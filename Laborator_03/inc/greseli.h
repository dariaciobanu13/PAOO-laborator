#ifndef GRESELI_H
#define GRESELI_H

// classes written WRONG on purpose, to show what happens
// when the destructor / copy constructor / move constructor is missing

#include <cstddef>
#include <iostream>
#include <string>

// mistake 1: allocates on the heap but has no destructor -> memory leak
class EchipaFaraDestructor {
private:
    std::string nume;
    std::string* jucatori;

public:
    inline static int alocari = 0;

    EchipaFaraDestructor(const std::string& numeEchipa, std::size_t cap)
        : nume(numeEchipa), jucatori(new std::string[cap])
    {
        ++alocari;
        std::cout << "[NoDestructor] Constructor \"" << nume << "\": allocated players at "
                  << jucatori << "\n";
    }
    // missing: ~EchipaFaraDestructor() { delete[] jucatori; }
};

// mistake 2: has a destructor but no copy constructor
// the one generated by the compiler only copies the POINTER (shallow copy)
class EchipaFaraCopy {
private:
    std::string nume;
    std::string* jucatori;
    std::size_t nrJucatori;
    std::size_t capacitate;

public:
    EchipaFaraCopy(const std::string& numeEchipa, std::size_t cap)
        : nume(numeEchipa), jucatori(new std::string[cap]), nrJucatori(0), capacitate(cap)
    {
        std::cout << "[NoCopy] Constructor \"" << nume << "\": allocated players at "
                  << jucatori << "\n";
    }

    ~EchipaFaraCopy()
    {
        std::cout << "[NoCopy] Destructor \"" << nume << "\": delete[] " << jucatori << "\n";
        delete[] jucatori;
    }

    void adaugaJucator(const std::string& jucator)
    {
        if (nrJucatori < capacitate) {
            jucatori[nrJucatori++] = jucator;
        }
    }

    void schimbaJucator(std::size_t index, const std::string& jucatorNou)
    {
        if (index < nrJucatori) {
            jucatori[index] = jucatorNou;
        }
    }

    void afiseaza() const
    {
        std::cout << "  \"" << nume << "\" (players at " << jucatori << "): ";
        for (std::size_t i = 0; i < nrJucatori; ++i) {
            std::cout << jucatori[i] << (i + 1 < nrJucatori ? ", " : "");
        }
        std::cout << "\n";
    }
};

// mistake 3: has destructor and copy constructor but no move constructor
// so std::move(...) doesn't move anything, it just calls the copy constructor
class EchipaFaraMove {
private:
    std::string nume;
    std::string* jucatori;
    std::size_t capacitate;

public:
    EchipaFaraMove(const std::string& numeEchipa, std::size_t cap)
        : nume(numeEchipa), jucatori(new std::string[cap]), capacitate(cap)
    {
        std::cout << "[NoMove] Constructor \"" << nume << "\": allocated players at "
                  << jucatori << "\n";
    }

    EchipaFaraMove(const EchipaFaraMove& other)
        : nume(other.nume), jucatori(new std::string[other.capacitate]),
          capacitate(other.capacitate)
    {
        for (std::size_t i = 0; i < capacitate; ++i) {
            jucatori[i] = other.jucatori[i];
        }
        std::cout << "[NoMove] Copy constructor \"" << nume << "\": allocated again and copied "
                  << capacitate << " slots (" << other.jucatori << " -> " << jucatori << ")\n";
    }

    ~EchipaFaraMove()
    {
        std::cout << "[NoMove] Destructor \"" << nume << "\": delete[] " << jucatori << "\n";
        delete[] jucatori;
    }
};

#endif
